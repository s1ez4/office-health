// Пакет version хранит номер версии программы.
//
// В коде написано "dev" — так называется любая сборка «у себя на компьютере». Настоящий номер
// подставляется при сборке релиза флагом компоновщика:
//
//	go build -ldflags "-X office-health/version.Version=1.2.3" .
//
// -X говорит: «в пакете office-health/version переменной Version присвой строку 1.2.3».
// Работает только с переменными (var) строкового типа — с константами (const) нельзя.
package version

// Version — номер версии без «v»: "1.2.3". "dev" — собрано вручную, не из релиза.
var Version = "dev"

// IsRelease — это настоящий релиз (а не ручная сборка)? Ручные сборки не обновляются сами,
// иначе при разработке программа подменяла бы себя последним релизом.
func IsRelease() bool { return Version != "dev" && Version != "" }
